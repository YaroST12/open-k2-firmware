"""Compress tools/web/k2.html and emit it as a C++ source for the firmware (build/web_asset.cpp).

The page is minified first (see minify) and the gzip stream is deterministic (mtime 0, no name),
so identical pages give identical images. With the `zopfli` CLI on PATH (the builder image has it)
the stream comes from zopfli (--i100, about 4 % smaller than gzip -9); without it, gzip -9.
Usage: embed_web.py <k2.html> <out.cpp>
"""
import gzip
import io
import re
import shutil
import subprocess
import sys
import tempfile


def minify(page: bytes) -> bytes:
    """Line-level, semantics-preserving shrink of the served page.

    Drops leading indentation on every line and whole-line `//` comments inside <script>
    blocks. Lines inside a JS template literal are left untouched; trailing comments are kept
    (a `//` after code may sit in a string such as a URL). The source page stays readable.
    """
    out = []
    in_script = in_tpl = False
    for line in page.split(b"\n"):
        if in_tpl:
            out.append(line)
            if line.count(b"`") % 2:
                in_tpl = False
            continue
        body = line.lstrip(b" \t")
        if in_script and body.startswith(b"//"):
            continue
        if re.search(rb"<script\b", body):
            in_script = True
        if b"</script>" in body:
            in_script = False
        if in_script and body.count(b"`") % 2:
            in_tpl = True
        out.append(body)
    return b"\n".join(out)


def compress(data: bytes, use_zopfli=None) -> bytes:
    """gzip stream of `data`: zopfli when available (or forced), else gzip -9. Both deterministic."""
    exe = shutil.which("zopfli") if use_zopfli is not False else None
    if exe:
        with tempfile.NamedTemporaryFile(suffix=".html") as f:
            f.write(data)
            f.flush()
            return subprocess.run([exe, "--i100", "-c", f.name], check=True, capture_output=True).stdout
    buf = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buf, compresslevel=9, mtime=0) as z:
        z.write(data)
    return buf.getvalue()


def render(page: bytes) -> str:
    blob = compress(minify(page))
    rows = []
    for i in range(0, len(blob), 16):
        rows.append("    " + ", ".join("0x%02x" % b for b in blob[i:i + 16]) + ",")
    return (
        "// Generated by tools/embed_web.py from tools/web/k2.html; do not edit.\n"
        '#include "k2/net/web_asset.hpp"\n\n'
        "namespace k2 {\n"
        "namespace {\n"
        "alignas(4) constexpr unsigned char kData[] = {\n" + "\n".join(rows) + "\n};\n"
        "}  // namespace\n\n"
        "WebAsset web_asset() { return {kData, sizeof kData, true}; }\n\n"
        "}  // namespace k2\n"
    )


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    with open(argv[1], "rb") as f:
        page = f.read()
    with open(argv[2], "w") as f:
        f.write(render(page))


if __name__ == "__main__":
    main(sys.argv)
