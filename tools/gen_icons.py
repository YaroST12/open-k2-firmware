"""Generate include/k2/ui/ui_icons.hpp-adjacent data (src/ui/ui_icons.cpp) from the ICONS table of
docs/ui_mockups/render_mockups.py, so firmware and mockups share one set of 12x12 masks.

Usage: tools/gen_icons.py [--check]   (--check exits 1 when src/ui/ui_icons.cpp is out of date)
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/ui_mockups/render_mockups.py"
OUT = ROOT / "src/ui/ui_icons.cpp"


def load_icons():
    tree = ast.parse(SRC.read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "ICONS":
            return ast.literal_eval(node.value)
    raise SystemExit("ICONS not found")


def render():
    icons = load_icons()
    out = ["// Generated by tools/gen_icons.py from docs/ui_mockups/render_mockups.py. Do not edit.",
           '#include "k2/ui/ui_icons.hpp"', "", "namespace k2 {", "",
           "// One 12-bit row per line, bit 11 = leftmost pixel.",
           "const uint16_t kIconBits[kIconCount][kIconSize] = {"]
    for key, rows in icons.items():
        assert len(rows) == 12 and all(len(r) == 12 for r in rows), key
        vals = ", ".join("0x%03X" % int("".join("1" if c == "#" else "0" for c in r), 2) for r in rows)
        out.append(f"    {{{vals}}},   // {key}")
    out += ["};", "", "}  // namespace k2", ""]
    return "\n".join(out), list(icons)


if __name__ == "__main__":
    text, names = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print("icons:", " ".join(names))
