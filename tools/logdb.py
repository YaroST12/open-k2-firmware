"""Compact log lines: the format table and the decoder (see include/k2/core/log.hpp).

The firmware never stores the K2LOG("[TAG] fmt", args) format strings; it emits
    msg#<id> <arg> <arg>...
(%d args signed decimal, %u/%x/%X/%c args unsigned hex, %s args %XX-escaped). This tool keeps
tools/logdb.json, the append-only id -> format table (an ID is never reused, so any older
firmware still decodes), and turns those lines back into text.

    python3 tools/logdb.py gen OUT.hpp       # build step: scan src/ include/, extend logdb.json,
                                             # write the k2::logdb::id() header (only if changed)
    python3 tools/logdb.py check             # every K2LOG format has an ID in logdb.json
    python3 tools/logdb.py decode [FILE...]  # decode LOG.TXT / a saved log / stdin (a tty pipe)

Library use (k2_flasher monitor, proto_lab): decode_line(line) / decode_text(text); an unknown
ID is left as "msg#<id> args".
"""
import json
import re
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
DB_PATH = ROOT / "tools/logdb.json"
SCAN_DIRS = ("src", "include")

_MSG = re.compile(r"^msg#(\d+)((?: [^ \n]*)*)$")
_CONV = re.compile(r"%(\d*)(.?)", re.S)
_CALL = re.compile(r"\bK2LOG\(\s*")
_LIT = re.compile(r'"((?:[^"\\\n]|\\.)*)"\s*')
_ESC = {"n": "\n", "t": "\t", "r": "\r", "\\": "\\", '"': '"', "'": "'", "0": "\0"}


# ---- table -------------------------------------------------------------------------------------

def load(path=DB_PATH):
    """id (int) -> format; {} when the table is missing or unreadable."""
    try:
        return {int(k): v for k, v in json.loads(Path(path).read_text())["messages"].items()}
    except (OSError, ValueError, KeyError):
        return {}


def _unescape_c(s):
    return re.sub(r"\\(x[0-9A-Fa-f]{2}|.)",
                  lambda m: chr(int(m.group(1)[1:], 16)) if m.group(1)[0] == "x" else _ESC.get(m.group(1), m.group(1)), s)


def scan_text(text):
    """Formats of every K2LOG(...) call: adjacent string literals joined, C escapes resolved."""
    out = []
    for m in _CALL.finditer(text):
        pos, parts = m.end(), []
        while (lit := _LIT.match(text, pos)):
            parts.append(_unescape_c(lit.group(1)))
            pos = lit.end()
        if parts:
            out.append("".join(parts))
    return out


def scan_tree(root=ROOT):
    fmts = []
    for d in SCAN_DIRS:
        for p in sorted((root / d).rglob("*")):
            if p.suffix in (".cpp", ".hpp", ".h") and p.name != "log.hpp":
                fmts += scan_text(p.read_text(errors="replace"))
    return fmts


def assign(db, fmts):
    """Append-only: known formats keep their ID, new ones get the next free one."""
    db = dict(db)
    known = set(db.values())
    nxt = max((int(k) for k in db), default=0) + 1
    for f in fmts:
        if f not in known:
            db[str(nxt)] = f
            known.add(f)
            nxt += 1
    return db


def _c_literal(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\{ord(ch):03o}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def header(db):
    rows = "\n".join(f"    {{{int(k)}, {_c_literal(v)}}}," for k, v in sorted(db.items(), key=lambda kv: int(kv[0])))
    return f"""// GENERATED by tools/logdb.py from tools/logdb.json - do not edit.
// Only used in constant evaluation: none of these strings reaches the firmware image.
#pragma once
#include <cstdint>
#include <string_view>

namespace k2::logdb {{

struct Entry {{
    std::uint16_t id;
    std::string_view fmt;
}};

inline constexpr Entry kEntries[] = {{
{rows}
}};

void format_missing_from_tools_logdb_json();   // never defined: names the error

consteval std::uint16_t id(std::string_view fmt) {{
    for (const Entry& e : kEntries)
        if (e.fmt == fmt) return e.id;
    format_missing_from_tools_logdb_json();
    return 0;
}}

}}  // namespace k2::logdb
"""


def _write_if_changed(path, text):
    path = Path(path)
    if path.exists() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


def db_json(db):
    msgs = {k: db[k] for k in sorted(db, key=int)}
    return json.dumps({"comment": "append-only K2LOG id -> format table, see tools/logdb.py",
                       "messages": msgs}, indent=1, ensure_ascii=False) + "\n"


# ---- decoder -----------------------------------------------------------------------------------

def _unescape_arg(a):
    """%XX -> byte; an escape cut off by the 64-byte line limit becomes '?'."""
    a = re.sub(r"%[0-9A-F]?$", "?", a)
    return unquote(a, errors="replace")   # %XX are UTF-8 bytes


def _render(fmt, args):
    """k2::fmt::vformat semantics: %d %u %x %X %s %c %%, '0' flag and width; %x is upper-case."""
    it = iter(args)
    out, i = [], 0
    while i < len(fmt):
        c = fmt[i]
        if c != "%" or i + 1 >= len(fmt):
            out.append(c)
            i += 1
            continue
        i += 1
        zero = fmt[i] == "0"
        width = 0
        while fmt[i].isdigit() and i + 1 < len(fmt):
            width = width * 10 + int(fmt[i])
            i += 1
        conv = fmt[i]
        i += 1
        if conv not in "duxXsc":
            out.append(conv)
            continue
        a = next(it, None)
        if conv == "s":
            out.append("?" if a is None else _unescape_arg(a))
            continue
        try:
            v = int(a, 10 if conv == "d" else 16)
        except (TypeError, ValueError):
            out.append("?")
            continue
        if conv == "c":
            out.append(chr(v & 0xFF))
            continue
        neg = v < 0
        digits = (f"{abs(v):d}" if conv in "du" else f"{abs(v):X}")
        total = len(digits) + neg
        pad = max(0, width - total)
        out.append((" " * pad if not zero else "") + ("-" if neg else "") + ("0" * pad if zero else "") + digits)
    return "".join(out)


_DB_CACHE = None


def decode_line(line, db=None):
    """One log line (with or without its newline). Plain text and unknown IDs pass through."""
    global _DB_CACHE
    nl = line.endswith("\n")
    m = _MSG.match(line[:-1] if nl else line)
    if not m:
        return line
    if db is None:
        if _DB_CACHE is None:
            _DB_CACHE = load()
        db = _DB_CACHE
    fmt = db.get(int(m.group(1)))
    if fmt is None:
        return line
    text = _render(fmt, m.group(2).split(" ")[1:] if m.group(2) else [])
    return text if text.endswith("\n") or not nl else text + "\n"


def decode_text(text, db=None):
    return "".join(decode_line(line, db) for line in text.splitlines(keepends=True))


# ---- cli ---------------------------------------------------------------------------------------

def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    cmd = argv[0]
    if cmd == "gen":
        db = assign({str(k): v for k, v in load().items()}, scan_tree())
        _write_if_changed(DB_PATH, db_json(db))
        _write_if_changed(argv[1], header(db))
        return 0
    if cmd == "check":
        db = load()
        missing = [f for f in scan_tree() if f not in set(db.values())]
        for f in missing:
            print("not in tools/logdb.json:", repr(f))
        return 1 if missing else 0
    if cmd == "decode":
        db = load()
        if len(argv) > 1:
            for p in argv[1:]:
                sys.stdout.write(decode_text(Path(p).read_text(errors="replace"), db))
        else:
            for line in sys.stdin:
                sys.stdout.write(decode_line(line, db))
                sys.stdout.flush()
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
